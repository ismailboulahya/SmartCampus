CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type_utilisateur VARCHAR(20) NOT NULL,
    nom VARCHAR(100) NOT NULL,
    prenom VARCHAR(100) NOT NULL,
    email VARCHAR(180) NOT NULL,
    mdp_hash VARCHAR(100) NOT NULL,
    date_creation TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    photo_profil_url VARCHAR(500),
    photo_couverture_url VARCHAR(500),
    nbr_connexion_echouee INTEGER NOT NULL DEFAULT 0,
    est_verrouille BOOLEAN NOT NULL DEFAULT FALSE,
    fin_verrouillage TIMESTAMP,
    cne VARCHAR(20),
    cin VARCHAR(20),
    filiere VARCHAR(20),
    niveau VARCHAR(20),
    matricule VARCHAR(30),
    departement VARCHAR(30),
    service_administratif VARCHAR(100),
    niveau_acces VARCHAR(50),
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT uk_users_cne UNIQUE (cne),
    CONSTRAINT uk_users_cin UNIQUE (cin)
);
