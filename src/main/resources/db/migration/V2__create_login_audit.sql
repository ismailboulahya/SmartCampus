-- =============================================================
-- V2 : journal des tentatives de connexion
-- user_id est NULL quand l'email ne correspond à aucun compte.
-- =============================================================
CREATE TABLE login_audit (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(255)             NOT NULL,
    user_id       BIGINT,
    success       BOOLEAN                  NOT NULL,
    reason        VARCHAR(30)              NOT NULL,
    ip_address    VARCHAR(45),
    attempted_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_login_audit_user FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE SET NULL
);

CREATE INDEX idx_login_audit_email_date ON login_audit (email, attempted_at);
