CREATE TABLE rooms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(100) NOT NULL,
    capacite INTEGER NOT NULL,
    date_creation TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_modification TIMESTAMP,
    CONSTRAINT uk_rooms_nom UNIQUE (nom),
    CONSTRAINT ck_rooms_capacite CHECK (capacite > 0)
);

CREATE TABLE room_equipements (
    room_id BIGINT NOT NULL,
    type_equipement VARCHAR(30) NOT NULL,
    CONSTRAINT fk_room_equipements_room FOREIGN KEY (room_id) REFERENCES rooms (id) ON DELETE CASCADE
);
